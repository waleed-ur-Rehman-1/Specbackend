/* ================================================================== *
 * MARKDOWN → BLOCKS
 * The SRS uses a small markdown subset — headings, bullets, tables,
 * blockquotes, horizontal rules, inline bold/italic/code. We do not
 * need a full parser; this covers everything the generator emits.
 * ================================================================== */

function parseMarkdown(md) {
  const lines = String(md || '').replace(/\r\n?/g, '\n').split('\n');
  const blocks = [];
  let i = 0;

  while (i < lines.length) {
    const raw = lines[i];
    const trimmed = raw.trim();

    if (!trimmed) {
      i += 1;
      continue;
    }

    // Heading (# / ## / ### / ####)
    const h = trimmed.match(/^(#{1,4})\s+(.*)$/);
    if (h) {
      blocks.push({ type: 'heading', level: h[1].length, text: stripInline(h[2]) });
      i += 1;
      continue;
    }

    // Horizontal rule
    if (/^-{3,}$/.test(trimmed)) {
      blocks.push({ type: 'hr' });
      i += 1;
      continue;
    }

    // Blockquote (consecutive lines starting with >)
    if (trimmed.startsWith('>')) {
      const buf = [];
      while (i < lines.length && lines[i].trim().startsWith('>')) {
        buf.push(lines[i].trim().replace(/^>\s?/, ''));
        i += 1;
      }
      blocks.push({ type: 'quote', text: stripInline(buf.join(' ')) });
      continue;
    }

    // Table (consecutive lines starting with |)
    if (trimmed.startsWith('|')) {
      const rows = [];
      while (i < lines.length && lines[i].trim().startsWith('|')) {
        const cells = lines[i]
          .trim()
          .replace(/^\||\|$/g, '')
          .split('|')
          .map((c) => stripInline(c.trim()));
        // Skip |---|---| separator rows
        if (!/^[-: ]+$/.test(cells.join(''))) {
          rows.push(cells);
        }
        i += 1;
      }
      if (rows.length) blocks.push({ type: 'table', rows });
      continue;
    }

    // Unordered list (consecutive lines starting with -, *, •)
    if (/^[-*•]\s+/.test(trimmed)) {
      const items = [];
      while (i < lines.length && /^[-*•]\s+/.test(lines[i].trim())) {
        items.push(stripInline(lines[i].trim().replace(/^[-*•]\s+/, '')));
        i += 1;
      }
      blocks.push({ type: 'list', items });
      continue;
    }

    // Numbered list
    if (/^\d+[.)]\s+/.test(trimmed)) {
      const items = [];
      while (i < lines.length && /^\d+[.)]\s+/.test(lines[i].trim())) {
        items.push(stripInline(lines[i].trim().replace(/^\d+[.)]\s+/, '')));
        i += 1;
      }
      blocks.push({ type: 'numbered', items });
      continue;
    }

    // Paragraph (gather until blank or block start)
    const para = [trimmed];
    i += 1;
    while (i < lines.length) {
      const t = lines[i].trim();
      if (!t) break;
      if (/^(#{1,4}\s|[-*•]\s|\d+[.)]\s|>|\||-{3,}$)/.test(t)) break;
      para.push(t);
      i += 1;
    }
    blocks.push({ type: 'paragraph', text: stripInline(para.join(' ')) });
  }

  return blocks;
}

function stripInline(s) {
  return String(s)
    .replace(/\*\*(.+?)\*\*/g, '$1')
    .replace(/\*(.+?)\*/g, '$1')
    .replace(/`(.+?)`/g, '$1')
    .replace(/\[(.+?)\]\(.+?\)/g, '$1');
}

/* ================================================================== *
 * PDF — SRS only (portrait A4)
 * ================================================================== */

export function streamPdf(res, { title, markdown, fileName }) {
  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader(
    'Content-Disposition',
    `attachment; filename="${safeName(fileName || title)}.pdf"`
  );

  const doc = new PDFDocument({ size: 'A4', margin: 56 });
  doc.pipe(res);

  // Cover
  doc.font('Helvetica-Bold').fontSize(24).fillColor('#111111').text(title, { align: 'center' });
  doc.moveDown(0.3);
  doc
    .font('Helvetica')
    .fontSize(11)
    .fillColor('#666666')
    .text('Generated by SpecForge', { align: 'center' });
  doc.moveDown(2);
  doc.fillColor('#000000');

  const blocks = parseMarkdown(markdown);

  for (const b of blocks) {
    switch (b.type) {
      case 'heading': {
        const size = { 1: 18, 2: 15, 3: 13, 4: 12 }[b.level] || 12;
        doc.moveDown(0.6);
        doc.font('Helvetica-Bold').fontSize(size).fillColor('#111111').text(b.text);
        doc.moveDown(0.3);
        doc.font('Helvetica').fillColor('#000000');
        break;
      }
      case 'paragraph':
        doc.font('Helvetica').fontSize(10).fillColor('#222222').text(b.text);
        doc.moveDown(0.5);
        break;
      case 'quote':
        doc
          .font('Helvetica-Oblique')
          .fontSize(10)
          .fillColor('#444444')
          .text(b.text, { indent: 20 });
        doc.moveDown(0.5);
        doc.font('Helvetica').fillColor('#000000');
        break;
      case 'list':
        for (const item of b.items) {
          doc.font('Helvetica').fontSize(10).text(`• ${item}`, { indent: 12 });
        }
        doc.moveDown(0.5);
        break;
      case 'numbered':
        b.items.forEach((item, idx) => {
          doc.font('Helvetica').fontSize(10).text(`${idx + 1}. ${item}`, { indent: 12 });
        });
        doc.moveDown(0.5);
        break;
      case 'table':
        for (const row of b.rows) {
          doc.font('Helvetica').fontSize(9).text(row.join('  |  '));
        }
        doc.moveDown(0.5);
        break;
      case 'hr':
        doc.moveDown(0.5);
        doc
          .strokeColor('#dddddd')
          .lineWidth(0.5)
          .moveTo(doc.page.margins.left, doc.y)
          .lineTo(doc.page.width - doc.page.margins.right, doc.y)
          .stroke();
        doc.moveDown(0.5);
        break;
      default:
        break;
    }
  }

  doc.end();
}

/* ================================================================== *
 * DOCX — SRS only
 * ================================================================== */

export async function buildDocxBuffer({ title, markdown }) {
  const children = [];

  // Cover page
  children.push(
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { after: 240 },
      children: [new TextRun({ text: title, bold: true, size: 44 })]
    })
  );
  children.push(
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { after: 720 },
      children: [new TextRun({ text: 'Generated by SpecForge', italics: true, size: 20 })]
    })
  );

  const blocks = parseMarkdown(markdown);

  for (const b of blocks) {
    switch (b.type) {
      case 'heading': {
        const level = {
          1: HeadingLevel.HEADING_1,
          2: HeadingLevel.HEADING_2,
          3: HeadingLevel.HEADING_3,
          4: HeadingLevel.HEADING_4
        }[b.level];
        children.push(new Paragraph({ text: b.text, heading: level }));
        break;
      }
      case 'paragraph':
        children.push(new Paragraph({ children: [new TextRun(b.text)] }));
        break;
      case 'quote':
        children.push(
          new Paragraph({
            children: [new TextRun({ text: b.text, italics: true })],
            indent: { left: 480 }
          })
        );
        break;
      case 'list':
        for (const item of b.items) {
          children.push(new Paragraph({ text: item, bullet: { level: 0 } }));
        }
        break;
      case 'numbered':
        for (const item of b.items) {
          children.push(
            new Paragraph({
              text: item,
              numbering: { reference: 'ordered-list', level: 0 }
            })
          );
        }
        break;
      case 'table': {
        const rows = b.rows.map((cells) => {
          const isHeader = cells === b.rows[0];
          return new TableRow({
            children: cells.map(
              (cell) =>
                new TableCell({
                  children: [
                    new Paragraph({
                      children: [new TextRun({ text: cell, bold: isHeader })]
                    })
                  ]
                })
            )
          });
        });
        children.push(
          new Table({
            width: { size: 100, type: WidthType.PERCENTAGE },
            rows
          })
        );
        children.push(new Paragraph(''));
        break;
      }
      case 'hr':
        children.push(
          new Paragraph({
            text: '',
            border: { bottom: { style: 'single', size: 6, color: 'CCCCCC' } }
          })
        );
        break;
      default:
        break;
    }
  }

  const doc = new Document({
    numbering: {
      config: [
        {
          reference: 'ordered-list',
          levels: [{ level: 0, format: 'decimal', text: '%1.' }]
        }
      ]
    },
    sections: [{ properties: {}, children }]
  });

  return Packer.toBuffer(doc);
}

/* ================================================================== *
 * PLANTUML PNG FETCH
 * ================================================================== */

async function fetchPlantUmlPng(encoded) {
  const server = (
    process.env.PLANTUML_SERVER || 'https://www.plantuml.com/plantuml'
  ).replace(/\/+$/, '');

  const response = await fetch(`${server}/png/${encoded}`, {
    signal: AbortSignal.timeout(20000)
  });
  if (!response.ok) throw new Error(`PlantUML server returned ${response.status}`);
  return Buffer.from(await response.arrayBuffer());
}

/* ================================================================== *
 * PDF — single diagram (landscape A4)
 * ================================================================== */

export async function streamDiagramPdf(res, { title, encoded, fileName }) {
  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader(
    'Content-Disposition',
    `attachment; filename="${safeName(fileName || title)}.pdf"`
  );

  let pngBuffer;
  try {
    pngBuffer = await fetchPlantUmlPng(encoded);
  } catch (err) {
    throw Object.assign(
      new Error(`Could not fetch diagram image from PlantUML server: ${err.message}`),
      { status: 502 }
    );
  }

  const doc = new PDFDocument({ size: 'A4', layout: 'landscape', margin: 40 });
  doc.pipe(res);

  doc.font('Helvetica-Bold').fontSize(16).fillColor('#111111').text(title, { align: 'center' });
  doc.moveDown(0.3);
  doc
    .font('Helvetica')
    .fontSize(9)
    .fillColor('#666666')
    .text('Rendered from PlantUML · Generated by SpecForge', { align: 'center' });
  doc.moveDown(1);

  const boxTop = doc.y;
  const boxWidth = doc.page.width - doc.page.margins.left - doc.page.margins.right;
  const boxHeight = doc.page.height - boxTop - doc.page.margins.bottom;

  doc.image(pngBuffer, doc.page.margins.left, boxTop, {
    fit: [boxWidth, boxHeight],
    align: 'center',
    valign: 'center'
  });

  doc.end();
}

/* ================================================================== *
 * PDF — full report (SRS + all diagrams + all tests)
 * ================================================================== */

const DIAGRAM_LABELS = {
  useCase: 'Use-Case Diagram',
  class: 'Class Diagram',
  sequence: 'Sequence Diagram',
  activity: 'Activity Diagram',
  state: 'State Diagram',
  er: 'Entity-Relationship Diagram'
};

export async function streamFullReportPdf(res, { title, markdown, diagrams, tests, fileName }) {
  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader(
    'Content-Disposition',
    `attachment; filename="${safeName(fileName || title)}.pdf"`
  );

  // Pre-fetch all diagram PNGs in parallel (non-fatal if any fail)
  const imageEntries = await Promise.all(
    Object.entries(diagrams || {}).map(async ([kind, diagram]) => {
      if (!diagram?.encoded) return null;
      try {
        const buf = await fetchPlantUmlPng(diagram.encoded);
        return [kind, buf];
      } catch (err) {
        console.warn(`[fullReportPdf] could not fetch ${kind} diagram:`, err.message);
        return null;
      }
    })
  );
  const images = Object.fromEntries(imageEntries.filter(Boolean));

  const doc = new PDFDocument({ size: 'A4', margin: 56, bufferPages: true });
  doc.pipe(res);

  /* ---------- Cover ---------- */
  doc.font('Helvetica-Bold').fontSize(28).fillColor('#111111').text(title, { align: 'center' });
  doc.moveDown(0.3);
  doc
    .font('Helvetica')
    .fontSize(13)
    .fillColor('#444444')
    .text('Software Requirements Specification', { align: 'center' });
  doc.moveDown(0.2);
  doc
    .fontSize(10)
    .fillColor('#666666')
    .text('Full report — SRS · UML diagrams · Acceptance tests', { align: 'center' });
  doc.moveDown(0.2);
  doc.text('Generated by SpecForge', { align: 'center' });
  doc.moveDown(3);

  /* ---------- SRS body ---------- */
  const blocks = parseMarkdown(markdown);
  for (const b of blocks) {
    switch (b.type) {
      case 'heading': {
        const size = { 1: 18, 2: 15, 3: 13, 4: 12 }[b.level] || 12;
        doc.moveDown(0.6);
        doc.font('Helvetica-Bold').fontSize(size).fillColor('#111111').text(b.text);
        doc.moveDown(0.3);
        doc.font('Helvetica').fillColor('#222222');
        break;
      }
      case 'paragraph':
        doc.font('Helvetica').fontSize(10).fillColor('#222222').text(b.text);
        doc.moveDown(0.5);
        break;
      case 'quote':
        doc
          .font('Helvetica-Oblique')
          .fontSize(10)
          .fillColor('#444444')
          .text(b.text, { indent: 20 });
        doc.moveDown(0.5);
        doc.font('Helvetica').fillColor('#222222');
        break;
      case 'list':
        for (const item of b.items) {
          doc.font('Helvetica').fontSize(10).text(`• ${item}`, { indent: 12 });
        }
        doc.moveDown(0.5);
        break;
      case 'numbered':
        b.items.forEach((item, idx) => {
          doc.font('Helvetica').fontSize(10).text(`${idx + 1}. ${item}`, { indent: 12 });
        });
        doc.moveDown(0.5);
        break;
      case 'table':
        for (const row of b.rows) {
          doc.font('Helvetica').fontSize(9).text(row.join('  |  '));
        }
        doc.moveDown(0.5);
        break;
      case 'hr':
        doc.moveDown(0.5);
        doc
          .strokeColor('#dddddd')
          .lineWidth(0.5)
          .moveTo(doc.page.margins.left, doc.y)
          .lineTo(doc.page.width - doc.page.margins.right, doc.y)
          .stroke();
        doc.moveDown(0.5);
        break;
      default:
        break;
    }
  }

  /* ---------- Diagram pages (landscape) ---------- */
  for (const [kind, buf] of Object.entries(images)) {
    doc.addPage({ size: 'A4', layout: 'landscape', margin: 40 });
    const label = DIAGRAM_LABELS[kind] || `${kind} diagram`;

    doc
      .font('Helvetica-Bold')
      .fontSize(16)
      .fillColor('#111111')
      .text(`${title} — ${label}`, { align: 'center' });
    doc.moveDown(1);

    const boxTop = doc.y;
    const boxWidth = doc.page.width - doc.page.margins.left - doc.page.margins.right;
    const boxHeight = doc.page.height - boxTop - doc.page.margins.bottom;

    doc.image(buf, doc.page.margins.left, boxTop, {
      fit: [boxWidth, boxHeight],
      align: 'center',
      valign: 'center'
    });
  }

  /* ---------- Acceptance tests appendix (portrait) ---------- */
  if (tests && tests.length) {
    doc.addPage({ size: 'A4', margin: 56 });
    doc
      .font('Helvetica-Bold')
      .fontSize(22)
      .fillColor('#111111')
      .text('Appendix — Acceptance Tests');
    doc.moveDown(0.4);
    doc
      .font('Helvetica')
      .fontSize(10)
      .fillColor('#666666')
      .text(`${tests.length} scenario(s) generated by SpecForge.`);
    doc.moveDown(1);

    for (const test of tests) {
      doc
        .font('Helvetica-Bold')
        .fontSize(12)
        .fillColor('#111111')
        .text(test.title || test.useCase || 'Scenario');
      doc.moveDown(0.2);
      doc
        .font('Courier')
        .fontSize(9)
        .fillColor('#333333')
        .text(test.gherkinText || test.code || '', { lineGap: 1 });
      doc.moveDown(0.8);
    }
  }

  /* ---------- Footer on every page ---------- */
  const range = doc.bufferedPageRange();
  for (let i = range.start; i < range.start + range.count; i += 1) {
    doc.switchToPage(i);
    doc
      .font('Helvetica')
      .fontSize(8)
      .fillColor('#999999')
      .text(
        `SpecForge · ${title} · Page ${i + 1} of ${range.count}`,
        doc.page.margins.left,
        doc.page.height - 30,
        {
          align: 'center',
          width: doc.page.width - doc.page.margins.left - doc.page.margins.right
        }
      );
  }

  doc.end();
}

/* ================================================================== *
 * Utility
 * ================================================================== */

function safeName(value) {
  return String(value || 'export')
    .replace(/[^\w.-]+/g, '_')
    .slice(0, 60);
}